const DAY_MS = 86_400_000;

export function getDailyMessage(date: Date) {
  const dayNumber = Math.floor(
    Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / DAY_MS,
  );
  return MESSAGES[dayNumber % MESSAGES.length];
}
